use std::{
    env,
    fmt::{Debug, Display},
    fs::File,
    io::{BufWriter, Write},
    path::PathBuf,
    str::FromStr,
};

fn parse_env_var<T>(name: &str) -> String
where
    T: Display,
    T: FromStr,
    <T as FromStr>::Err: Debug,
{
    match env::var(name) {
        Ok(val) => {
            let num = val
                .parse::<T>()
                .unwrap_or_else(|_| panic!("{name} must be valid {}!", std::any::type_name::<T>()));
            format!("Some({})", num)
        }
        Err(_) => "None".to_string(),
    }
}

fn main() {
    linker_be_nice();

    println!("cargo:rerun-if-env-changed=BOARD");

    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let path = &out.join("env_vars.rs");
    let mut file = BufWriter::new(File::create(path).unwrap());

    // 0 -> GW, 1 -> A, 2 -> B
    let board_code: String = parse_env_var::<u8>("BOARD");

    write!(
        &mut file,
        "{}",
        format_args!(
            "\
            // Generated by build.rs\n\
            const BOARD_OPT: Option<u8> = {};\n",
            board_code,
        )
    )
    .unwrap();

    println!("cargo:rustc-link-arg=-Tdefmt.x");
    // make sure linkall.x is the last linker script (otherwise might cause problems with flip-link)
    println!("cargo:rustc-link-arg=-Tlinkall.x");
}

fn linker_be_nice() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() > 1 {
        let kind = &args[1];
        let what = &args[2];

        match kind.as_str() {
            "undefined-symbol" => match what.as_str() {
                what if what.starts_with("_defmt_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `defmt` not found - make sure `defmt.x` is added as a linker script and you have included `use defmt_rtt as _;`"
                    );
                    eprintln!();
                }
                "_stack_start" => {
                    eprintln!();
                    eprintln!("💡 Is the linker script `linkall.x` missing?");
                    eprintln!();
                }
                what if what.starts_with("esp_rtos_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `esp-radio` has no scheduler enabled. Make sure you have initialized `esp-rtos` or provided an external scheduler."
                    );
                    eprintln!();
                }
                "embedded_test_linker_file_not_added_to_rustflags" => {
                    eprintln!();
                    eprintln!(
                        "💡 `embedded-test` not found - make sure `embedded-test.x` is added as a linker script for tests"
                    );
                    eprintln!();
                }
                "free"
                | "malloc"
                | "calloc"
                | "get_free_internal_heap_size"
                | "malloc_internal"
                | "realloc_internal"
                | "calloc_internal"
                | "free_internal" => {
                    eprintln!();
                    eprintln!(
                        "💡 Did you forget the `esp-alloc` dependency or didn't enable the `compat` feature on it?"
                    );
                    eprintln!();
                }
                _ => (),
            },
            // we don't have anything helpful for "missing-lib" yet
            _ => {
                std::process::exit(1);
            }
        }

        std::process::exit(0);
    }

    println!(
        "cargo:rustc-link-arg=--error-handling-script={}",
        std::env::current_exe().unwrap().display()
    );
}
