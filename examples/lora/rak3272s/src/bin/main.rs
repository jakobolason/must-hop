const DEFAULT_SOURCEID: u8 = 2;
const DEFAULT_KI: i64 = 25;
const DEFAULT_KP: i64 = 20;
const DEFAULT_TAU: u8 = 10;
const DEFAULT_ALT_MDLTN: bool = false;

bind_interrupts!(struct Irqs{
    SUBGHZ_RADIO => InterruptHandler;
    RNG => rng::InterruptHandler<peripherals::RNG>;
});

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let mut config = Config::default();
    {
        config.rcc.ls = LsConfig {
            rtc: RtcClockSource::LSE,
            lse: Some(LseConfig {
                frequency: Hertz(32_768),
                mode: LseMode::Oscillator(LseDrive::High),
                peripherals_clocked: true,
            }),
            lsi: false,
        };
        config.rcc.msi = Some(MSIRange::RANGE48M);
        config.rcc.sys = Sysclk::MSI;
        config.rcc.mux.rngsel = mux::Rngsel::MSI;
        config.enable_debug_during_sleep = true;
    }
    let p = embassy_stm32::init(config);
    info!("Checking this: {}", embassy_stm32::pac::RCC.cr().read());
    let bdcr = embassy_stm32::pac::RCC.bdcr().read();
    info!(
        "BDCR: lseon={} lserdy={} rtcsel={}",
        bdcr.lseon(),
        bdcr.lserdy(),
        bdcr.rtcsel() as u8
    );
    // confirm LSE is actually ready (this is the only documented precondition)
    while !embassy_stm32::pac::RCC.bdcr().read().lserdy() {}
    info!("LSE confirmed ready; attempting MSIPLLEN=1");

    // write and read back immediately
    embassy_stm32::pac::RCC
        .cr()
        .modify(|w| w.set_msipllen(true));
    let after = embassy_stm32::pac::RCC.cr().read();
    info!("after manual write: msipllen={}", after.msipllen());

    info!("config done...");
    let rx_pin = Output::new(p.PB8, Level::Low, Speed::VeryHigh);
    let tx_pin = Output::new(p.PC13, Level::Low, Speed::VeryHigh);

    let spi = Spi::new_subghz(p.SUBGHZSPI, p.DMA1_CH1, p.DMA1_CH2);
    let spi = SubghzSpiDevice(spi);
    // TODO: Can it work wit low power?
    let use_high_power_pa = false;
    let config = sx126x::Config {
        chip: Stm32wl { use_high_power_pa },
        tcxo_ctrl: None,
        use_dcdc: true,
        rx_boost: false,
    };
    let iv: Stm32wlInterfaceVariant<Output<'_>> =
        Stm32wlInterfaceVariant::new(Irqs, use_high_power_pa, Some(rx_pin), Some(tx_pin), None)
            .unwrap();
    // The SX1302 HAL hardcodes the private syncword (0x12) for SF5 and SF6,
    // regardless of the lorawan_public board setting. We must match that here.
    let use_public_network = SF_NUM != 5 && SF_NUM != 6;
    let lora = LoRa::new(Sx126x::new(spi, iv, config), use_public_network, Delay)
        .await
        .unwrap();
    info!("lora setup done ...");
    let debug_pin = Output::new(p.PA2, Level::Low, Speed::VeryHigh);

    if let Err(e) = spawner.spawn(lora_task(lora, CHANNEL.receiver(), debug_pin)) {
        error!("error in spawning lora task: {:?}", e);
    }
    // TODO: Add sensor data creation task
    let rng = Rng::new(p.RNG, Irqs);
    if let Err(e) = spawner.spawn(sensor_task(CHANNEL.sender(), rng)) {
        error!("Error in spawning lora task: {:?}, ", e);
    }

    loop {
        info!("from main...");
        Timer::after_secs(10u64).await;
    }
}

#[embassy_executor::task]
async fn sensor_task(
    channel: channel::Sender<'static, ThreadModeRawMutex, SensorData, 3>,
    mut rng: Rng<'static, peripherals::RNG>, // Ensure 'mut' is here
) {
    Timer::after_secs(10).await;
    loop {
        let expected_packet = SensorData {
            device_id: 42,
            temperate: 23.5,
            voltage: 3.3,
            acceleration_x: 1.2,
        };
        channel.send(expected_packet).await;

        info!("Send a packet!");
        let random = rng.next_u64();
        // random number between 3 and 8
        let r_num = (random % 5) + 15;
        info!("waiting {} seconds ...", r_num);

        Timer::after_secs(r_num).await;
    }
}

/// From the study, sensor data will likely be between 20-40 bytes per transmission
const MAX_PACK_LEN: usize = 40;
const MAX_RADIO_BUFFER: usize = 256; // kB
const LEN: usize = 5; // floor(256/MAX_PACK_LEN)

const GW_ID: u8 = 1;

// Compute the MAX TOA MS as a const, such that it is evaluted at build time instead of runtime
const MAX_TOA_MS: u32 = {
    let sf = match SF {
        Some(sf) => sf,
        None => SpreadingFactor::_7,
    };
    let bw = match BW {
        Some(bw) => bw,
        None => Bandwidth::_125KHz,
    };
    BaseBandModulationParams::new(sf, bw, CodingRate::_4_8).time_on_air_us(Some(8), true, 140_u8)
        / 1000
};

#[embassy_executor::task]
pub async fn lora_task(
    mut lora: Stm32wlLoRa<'static, Master>,
    channel: channel::Receiver<'static, ThreadModeRawMutex, SensorData, 3>,
    debug_pin: Output<'static>,
) {
    let sf = SF.unwrap_or(SpreadingFactor::_7);
    let bw = BW.unwrap_or(Bandwidth::_125KHz);
    let cr = CodingRate::_4_8;
    info!("radio params: SF={} BW={}kHz", SF_NUM, BW_KHZ);
    let mp = RatioModParams {
        sf,
        bw,
        cr,
        lora_hz: LORA_FREQUENCY_IN_HZ,
    };
    let tp = RadioPackParams {
        pre_amp: 8,
        imp_hed: false,
        max_pack_len: MAX_PACK_LEN,
        crc: true,
        iq: false,
    };
    let source_id: u8 = SOURCEID.unwrap_or(DEFAULT_SOURCEID);

    // For experiment 2: Set bool such that it uses other SF for Rx
    // (GW) <-> (A) <-> (B)
    //          A is the only one who should use this here
    let should_have_alt_mdltn_params: bool = ALT_MDLTN.unwrap_or(DEFAULT_ALT_MDLTN);
    let alt_mdltn = if should_have_alt_mdltn_params {
        Some(RatioModParams {
            sf: SpreadingFactor::_7,
            bw,
            cr,
            lora_hz: LORA_FREQUENCY_IN_HZ,
        })
    } else {
        None
    };
    let timeout = 3;
    let max_retries = 3;
    let node = match LoraNode::<_, _, MAX_PACK_LEN, LEN>::new(&mut lora, tp, mp, alt_mdltn) {
        Ok(node) => node,
        Err(e) => {
            error!("Failed to initialize lora node: {:?}", e);
            return;
        }
    };
    // let mac = RandomAccessMac::new(NodePolicy);

    let ki = KI.unwrap_or(DEFAULT_KI);
    let kp = KP.unwrap_or(DEFAULT_KP);
    let tau = TAU.unwrap_or(DEFAULT_TAU);
    let mac = TdmaMac::default()
        .set_controller(-10_000, kp, ki)
        .set_debug_pin(debug_pin)
        .set_node_id(source_id)
        .set_max_toa(MAX_TOA_MS)
        .set_tau_hb(tau)
        .build();
    let nm =
        network_manager::NetworkManager::<MAX_PACK_LEN, LEN>::new(source_id, timeout, max_retries);
    let mut router = mesh_router::MeshRouter::new(node, nm, mac);

    loop {
        let mut receiving_buffer = [00u8; MAX_RADIO_BUFFER];

        // Before letting router do its thing, we check if we want to send something
        if let Ok(data) = channel.try_receive()
            // And call the router to send this data for us
            && let Err(e) = router.queue_payload(data.into(), GW_ID)
        {
            error!("Error queing sensor data: {:?}", e);
        }

        match router.tick(&mut receiving_buffer).await {
            Ok(my_pkts) => {
                if !my_pkts.is_empty() {
                    info!(
                        "received these packets for me!: {}, {}",
                        my_pkts.len(),
                        my_pkts[0].packet_id
                    )
                }
            }
            Err(mesh_router::MeshRouterError::Node(e)) => match e {
                RadioError::ReceiveTimeout => continue,
                _ => error!("Error in radio: {:?}", e),
            },
            Err(e) => error!("Error in ticking router; {:?}", e),
        }
    }

    // lora::lora_task(node, channel, source_id as u8, 3, 3, mac).await;
}

// This creates the task which checks for sensor data
// or someone trying to send data. This handles both receive and transmission logic
type Stm32wlLoRa<'d, CM> = LoRa<
    Sx126x<
        iv::SubghzSpiDevice<Spi<'d, Async, CM>>,
        iv::Stm32wlInterfaceVariant<Output<'d>>,
        Stm32wl,
    >,
    Delay,
>;

#[derive(Serialize, Deserialize, Debug, PartialEq, defmt::Format, Copy, Clone)]
pub struct SensorData {
    pub device_id: u8,
    pub temperate: f32,
    pub voltage: f32,
    pub acceleration_x: f32,
}

// TODO: Shuold not use this, only for prototyping
impl From<SensorData> for Vec<u8, MAX_PACK_LEN> {
    fn from(data: SensorData) -> Self {
        let mut buffer = [0u8; MAX_PACK_LEN];
        let slice = to_slice(&data, &mut buffer).expect("Could not serialize sensor data");
        Vec::from_slice(slice).expect("buffer too small")
    }
}
